/**
 * Review view of a call's arguments. A tool may declare top-level base64 fields in `redactArgs`;
 * each is replaced by its decoded size and the SHA-256 of the decoded bytes, so approvals and
 * audit never carry the payload yet stay bound to it. Pure and synchronous: `crypto.subtle` does
 * not exist when Foundry is served over plain http.
 */
declare const globalThis: { atob?: (data: string) => string };

