/** SHA-256 of raw bytes, as hex. Synchronous, pure JavaScript. */
export function sha256Bytes(bytes: Uint8Array): string {
  const bitLen = bytes.length * 8;
  const padded = new Uint8Array(Math.ceil((bytes.length + 9) / 64) * 64);
  padded.set(bytes);
  padded[bytes.length] = 0x80;
  const view = new DataView(padded.buffer);
  view.setUint32(padded.length - 8, Math.floor(bitLen / 0x100000000));
  view.setUint32(padded.length - 4, bitLen >>> 0);
  const h = new Uint32Array([
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
  ]);
  const w = new Uint32Array(64);
  const rotr = (x: number, n: number) => (x >>> n) | (x << (32 - n));
  for (let off = 0; off < padded.length; off += 64) {
    for (let i = 0; i < 16; i++) w[i] = view.getUint32(off + i * 4);
    for (let i = 16; i < 64; i++) {
      const s0 = rotr(w[i - 15]!, 7) ^ rotr(w[i - 15]!, 18) ^ (w[i - 15]! >>> 3);
      const s1 = rotr(w[i - 2]!, 17) ^ rotr(w[i - 2]!, 19) ^ (w[i - 2]! >>> 10);
      w[i] = (w[i - 16]! + s0 + w[i - 7]! + s1) >>> 0;
    }
    let [a, b, c, d, e, f, g, hh] = h as unknown as number[];
    for (let i = 0; i < 64; i++) {
      const S1 = rotr(e!, 6) ^ rotr(e!, 11) ^ rotr(e!, 25);
      const ch = (e! & f!) ^ (~e! & g!);
      const t1 = (hh! + S1 + ch + K[i]! + w[i]!) >>> 0;
      const S0 = rotr(a!, 2) ^ rotr(a!, 13) ^ rotr(a!, 22);
      const maj = (a! & b!) ^ (a! & c!) ^ (b! & c!);
      const t2 = (S0 + maj) >>> 0;
      hh = g;
      g = f;
      f = e;
      e = (d! + t1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) >>> 0;
    }
    const add = [a, b, c, d, e, f, g, hh] as number[];
    for (let i = 0; i < 8; i++) h[i] = (h[i]! + add[i]!) >>> 0;
  }
  return Array.from(h, (x) => x.toString(16).padStart(8, '0')).join('');
}

const BASE64 = /^[A-Za-z0-9+/]+={0,2}$/;

/** Decode strict base64, or null when it is not valid. */
export function decodeBase64Strict(data: string): Uint8Array | null {
  if (data.length % 4 !== 0 || !BASE64.test(data)) return null;
  let binary: string;
  try {
    binary = globalThis.atob!(data);
  } catch {
    return null;
  }
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

/** Returns `args` itself (same reference) unless the tool declares fields that are present. */
export function redactedArgs(
  info: { readonly redactArgs?: readonly string[] } | undefined,
  args: unknown,
): unknown {
  const fields = info?.redactArgs;
  if (!fields?.length || args === null || typeof args !== 'object' || Array.isArray(args))
    return args;
  const source = args as Record<string, unknown>;
  let out: Record<string, unknown> | undefined;
  for (const field of fields) {
    if (!Object.hasOwn(source, field)) continue;
    const value = source[field];
    if (typeof value !== 'string') continue;
    const bytes = decodeBase64Strict(value);
    out ??= { ...source };
    out[field] = bytes
      ? { redacted: true, bytes: bytes.length, sha256: sha256Bytes(bytes) }
      : { redacted: true, chars: value.length };
  }
  return out ?? args;
}
